  CONSTRAINT "HomeHealthStaffProfile_user_key" UNIQUE ("organizationId","legalEntityId","userId"),
  CONSTRAINT "HomeHealthStaffProfile_discipline_check" CHECK ("discipline" IN ('RN','LPN','PT','OT','ST','RT','HHA','MSW','OTHER')),
