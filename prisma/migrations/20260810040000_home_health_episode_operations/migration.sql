CREATE OR REPLACE FUNCTION "prevent_home_health_episode_event_mutation"()
RETURNS trigger AS $$ BEGIN RAISE EXCEPTION 'HomeHealthEpisodeEvent is append-only'; END; $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS "HomeHealthEpisodeEvent_no_update" ON "HomeHealthEpisodeEvent";
CREATE TRIGGER "HomeHealthEpisodeEvent_no_update" BEFORE UPDATE ON "HomeHealthEpisodeEvent" FOR EACH ROW EXECUTE FUNCTION "prevent_home_health_episode_event_mutation"();
DROP TRIGGER IF EXISTS "HomeHealthEpisodeEvent_no_delete" ON "HomeHealthEpisodeEvent";
CREATE TRIGGER "HomeHealthEpisodeEvent_no_delete" BEFORE DELETE ON "HomeHealthEpisodeEvent" FOR EACH ROW EXECUTE FUNCTION "prevent_home_health_episode_event_mutation"();
