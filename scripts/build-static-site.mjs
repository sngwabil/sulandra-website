import { mkdir, readdir, readFile, stat, writeFile, copyFile, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputDirectory = path.join(root, 'dist-web');

await rm(outputDirectory, { recursive: true, force: true });
await mkdir(outputDirectory, { recursive: true });

const excludedTopLevel = new Set([
  '.git', '.github', '.vercel', '.railway', '.idea', '.vscode',
  'api', 'node_modules', 'scripts', 'dist-web', 'uploads', 'coverage',
]);

async function copyTree(source, destination) {
  const entries = await readdir(source, { withFileTypes: true });
  for (const entry of entries) {
    if (source === root && excludedTopLevel.has(entry.name)) continue;
    const sourcePath = path.join(source, entry.name);
    const destinationPath = path.join(destination, entry.name);
    if (entry.isDirectory()) {
      await mkdir(destinationPath, { recursive: true });
      await copyTree(sourcePath, destinationPath);
    } else if (entry.isFile()) {
      await copyFile(sourcePath, destinationPath);
    }
  }
}

await copyTree(root, outputDirectory);

// Publish clean-route fallbacks for important static entry points.
const cleanRoutes = {
  policies: 'policies.html', documents: 'employee360.html', news: 'news.html', feedback: 'feedback.html',
  payroll: 'payroll.html', benefits: 'benefits.html', 'employee-directory': 'employee-directory.html', leadership: 'leadership.html',
  support: 'support.html', 'it-request': 'support.html', 'time-attendance': 'time-attendance.html', scheduling: 'scheduling.html',
  'incident-reporting': 'health-safety.html', 'health-safety': 'health-safety.html', 'service-request': 'service-request.html', resources: 'resources.html',
};
for (const [route, sourceFile] of Object.entries(cleanRoutes)) {
  const routeDirectory = path.join(outputDirectory, route);
  await mkdir(routeDirectory, { recursive: true });
  await copyFile(path.join(outputDirectory, sourceFile), path.join(routeDirectory, 'index.html'));
}

// Modern Admin is generated by later build scripts. This first publication pass keeps
// all source files available in dist-web so restore-modern-admin-portal.mjs can safely
// upgrade the copied admin.html and runtime assets in-place.

// The rest of this file is intentionally re-run after finalization by later scripts in
// the build chain. If we are already in the final publication state, verify that the
// canonical Admin shell and its production assets are present.
const publishedAdminPath = path.join(outputDirectory, 'admin.html');
let publishedAdmin = await readFile(publishedAdminPath, 'utf8');
const achievedArchiveScript = '<script src="/assets/admin-achieved-archive-fix.js?v=20260808-achieved-archive-1"></script>';
if (!publishedAdmin.includes('/assets/admin-achieved-archive-fix.js')) {
  publishedAdmin = publishedAdmin.replace('</body>', `${achievedArchiveScript}</body>`);
  await writeFile(publishedAdminPath, publishedAdmin, 'utf8');
}

// Accept only the current Admin Command Center runtime. The analog wall-clock runtime
// is a separate final asset loaded after the main dashboard so the Live Clock cannot
// silently fall back to the retired digital presentation.
for (const marker of [
  'sulandra-platform-bar',
  '/assets/admin-live-dashboard.js?v=20260808-admin-command-center-v5',
  '/assets/admin-analog-clock.js?v=20260808-analog-clock-v1',
  '/assets/sulandra-enterprise-owner.js?v=20260808-admin-profile-owner-v1',
  '/assets/admin-service-home-management-v2.js?v=20260808-admin-command-center-v4',
  '/assets/admin-platform-routing.js?v=20260808-daily-scheduling-v2',
  '/assets/admin-dashboard-cleanup.js?v=20260808-dashboard-cleanup-v1',
  '/assets/admin-achieved-archive-fix.js?v=20260808-achieved-archive-1',
  'id="admin-fullscreen-layout"',
]) {
  if (!publishedAdmin.includes(marker)) throw new Error(`Modern Admin publication failed; missing ${marker}`);
}

const requiredPublishedFiles = [
  'admin.html', 'admin-railway.js', 'employee-login.html', 'employee-portal.html',
  'employee360.html', 'education-portal.html', 'time-attendance.html', 'scheduling.html', 'intranet.html',
  'intranet.HTML', 'policies.html', 'news.html', 'feedback.html', 'payroll.html',
  'benefits.html', 'employee-directory.html', 'leadership.html', 'support.html',
  'health-safety.html', 'careers-admin-workflow.js', 'interview-admin-scheduler.js',
  'favicon-48x48.png', 'assets/mainlogo.png', 'assets/admin-platform-routing.js',
  'assets/admin-live-dashboard.js', 'assets/admin-analog-clock.js',
  'assets/admin-service-home-management-v2.js', 'assets/admin-dashboard-cleanup.js', 'assets/admin-achieved-archive-fix.js',
  'spire.html', 'spire-admin.html', 'services',
];
for (const relative of requiredPublishedFiles) {
  try { await stat(path.join(outputDirectory, relative)); }
  catch { throw new Error(`Static publication regression: missing ${relative}`); }
}

