import { access, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const requested=process.argv[2]||'it-solutions.html';
const portalPath=path.resolve(root,requested);
const cssPath=path.join(root,'assets','it-agent-workspace-preview.css');
const jsPath=path.join(root,'assets','it-agent-workspace-preview.js');
await Promise.all([access(portalPath),access(cssPath),access(jsPath)]);
let html=await readFile(portalPath,'utf8');
const cssTag='<link rel="stylesheet" href="/assets/it-agent-workspace-preview.css?v=20260901-workspace-ide-3">';
const jsTag='<script src="/assets/it-agent-workspace-preview.js?v=20260901-workspace-ide-3"></script>';
html=html.replace(/\s*<link rel="stylesheet" href="\/assets\/it-agent-workspace-preview\.css(?:\?v=[^"']+)?">\s*/g,'\n');
html=html.replace(/\s*<script src="\/assets\/it-agent-workspace-preview\.js(?:\?v=[^"']+)?"><\/script>\s*/g,'\n');
if(!html.includes('</head>')||!html.includes('</body>'))throw new Error('IT Solutions publication anchors changed');
html=html.replace('</head>',`${cssTag}</head>`).replace('</body>',`${jsTag}</body>`);
const css=await readFile(cssPath,'utf8');
const js=await readFile(jsPath,'utf8');
for(const marker of ['SULANDRA_WORKSPACE_IDE_PREVIEW_V1','itws-workspace-panel-open','itws-workspace-panel','itws-ide-mode','--itws-workspace-panel-height','--itws-terminal-available-height'])if(!css.includes(marker))throw new Error(`Workspace IDE CSS missing ${marker}`);
for(const marker of ['SULANDRA_WORKSPACE_IDE_PREVIEW_V1','itwsWorkspaceIdeButton','itwsWorkspacePreviewButton','/workspace/ticket','SulandraWorkspacePreview','9000','13337','syncPanelBounds','itws-ide-mode','itws-workspace-close','--itws-terminal-available-height'])if(!js.includes(marker))throw new Error(`Workspace IDE JavaScript missing ${marker}`);
if(/document\.addEventListener\(['"](?:pointerdown|mousedown)['"][\s\S]{0,500}closePanel/.test(js))throw new Error('Workspace IDE panel must not dismiss on workspace pointer activity');
await writeFile(portalPath,html,'utf8');
console.log(`Workspace IDE/live-preview controls published into ${requested}`);
